#!/usr/bin/env python3
"""Fit the company-board list to THIS profile and geo -> me/boards.txt (scan.py then uses it).

    jk boards            # check every board from config/ats_orgs.txt (+ your own lines), write me/boards.txt
    jk boards --dry      # report only

Per board, all open jobs (any age) are fetched once:
  keep  — has your roles now (title_include) in a geo that isn't blocked, OR hires in your geo at all
          (future roles likely);
  drop  — board empty now or wrong slug (re-run monthly: the seed list is re-checked every time), or every job is in a blocked region (e.g. US-only company).
Your own lines below "# mine" in me/boards.txt are always kept. ~1 minute for 300 boards.
"""
from __future__ import annotations

import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import kit  # noqa: E402
import scan  # noqa: E402

OUT = kit.ME / "boards.txt"
MINE = "# mine"


def own_lines() -> list[str]:
    if not OUT.exists():
        return []
    text = OUT.read_text(encoding="utf-8")
    return [l for l in text.split(MINE, 1)[1].splitlines() if l.strip()] if MINE in text else []


def main() -> int:
    gates = kit.Gates(kit.load_profile())
    seed = kit.FRAMEWORK / "config" / "ats_orgs.txt"
    orgs = []
    for line in seed.read_text().splitlines() + own_lines():
        p = line.split("#", 1)[0].split()
        if len(p) == 2 and p[0] in scan.ENGINES and (p[0], p[1]) not in orgs:
            orgs.append((p[0], p[1]))

    def check(o):
        jobs = scan.fetch_org(*o)
        geo = [gates.geo(j["location"]) for j in jobs]
        roles = sum(1 for j, g in zip(jobs, geo) if gates.title(j["title"]) and g != "blocked")
        local = sum(g == "wide" for g in geo)
        return o, len(jobs), roles, local, (bool(jobs) and geo.count("blocked") < len(jobs))

    with ThreadPoolExecutor(16) as ex:
        res = list(ex.map(check, orgs))
    keep = [r for r in res if r[2] > 0 or (r[4] and r[3] > 0)]
    dead = sum(1 for r in res if r[1] == 0)
    blocked = sum(1 for r in res if r[1] and not r[4])
    keep.sort(key=lambda r: (-r[2], -r[3]))

    print(f"boards {len(res)} · keep {len(keep)} · empty/dead {dead} · geo-blocked {blocked} · other-geo/no-fit {len(res) - len(keep) - dead - blocked}")
    print("top: " + ", ".join(f"{o[1]}({n})" for o, _, n, _, _ in keep[:15] if n))
    if "--dry" in sys.argv:
        return 0
    mine = own_lines()
    body = [f"# Generated by `jk boards` for your profile — re-run after changing roles or geo.",
            f"# columns after #: open jobs · your roles now · jobs in your geo", ""]
    body += [f"{o[0]} {o[1]}  # {t} · {n} · {l}" for o, t, n, l, _ in keep]
    body += ["", MINE + " — add your own companies below; always kept", *mine]
    kit.ME.mkdir(exist_ok=True)
    OUT.write_text("\n".join(body) + "\n", encoding="utf-8")
    print(f"written {OUT}")
    from events import log
    log("boards_fit", total=len(res), keep=len(keep), dead=dead, blocked=blocked)
    return 0


if __name__ == "__main__":
    sys.exit(main())
